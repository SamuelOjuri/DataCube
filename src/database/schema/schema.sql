    SELECT *
    FROM (VALUES
        ('category'::TEXT),
        ('type'::TEXT),
        ('product'::TEXT),
        ('account'::TEXT)
    ) AS dimensions(dimension)
),
project_signal_tokens AS (
    SELECT
        f.project_id,
        'category'::TEXT AS dimension,
        public.smoothing_normalize_token(f.category) AS group_key,
        NULLIF(BTRIM(f.category), '') AS group_display
    FROM forecast_projects f

    UNION ALL

    SELECT
        f.project_id,
        'type'::TEXT AS dimension,
        public.smoothing_normalize_token(f.type) AS group_key,
        NULLIF(BTRIM(f.type), '') AS group_display
    FROM forecast_projects f

    UNION ALL

    SELECT
        f.project_id,
        'product'::TEXT AS dimension,
        public.smoothing_normalize_token(product_token.token) AS group_key,
        NULLIF(BTRIM(product_token.token), '') AS group_display
    FROM forecast_projects f
    CROSS JOIN LATERAL REGEXP_SPLIT_TO_TABLE(
        COALESCE(f.product_type, ''),
        '[[:space:]]*,[[:space:]]*'
    ) AS product_token(token)

    UNION ALL

    SELECT
        f.project_id,
        'account'::TEXT AS dimension,
        public.smoothing_normalize_token(account_token.token) AS group_key,
        NULLIF(BTRIM(account_token.token), '') AS group_display
    FROM forecast_projects f
    CROSS JOIN LATERAL REGEXP_SPLIT_TO_TABLE(
        COALESCE(f.account, ''),
        '[[:space:]]*,[[:space:]]*'
    ) AS account_token(token)
),
