        COUNT(s.group_key) AS matched_signal_count,
        (COUNT(t.group_key) = 0 OR COUNT(s.group_key) < COUNT(t.group_key)) AS signal_fallback_used,
        ROUND(
            AVG(COALESCE(s.shrunk_mature_smoothed_pct, g.shrunk_mature_smoothed_pct)),
