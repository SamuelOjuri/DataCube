CREATE OR REPLACE FUNCTION public.invoice_smoothing_signal_members(
    p_as_of_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
    as_of_date DATE,
    project_id TEXT,
    dimension TEXT,
    group_key TEXT,
    group_display TEXT
) AS $$
    WITH training AS (
        SELECT *
        FROM public.invoice_smoothing_training_rows(COALESCE(p_as_of_date, CURRENT_DATE)::DATE)
    ),
    raw_members AS (
        SELECT
            t.as_of_date AS member_as_of_date,
            t.project_id,
            'category'::TEXT AS dimension,
            public.smoothing_normalize_token(t.category) AS group_key,
            NULLIF(BTRIM(t.category), '') AS group_display
        FROM training t

        UNION ALL

        SELECT
            t.as_of_date,
            t.project_id,
            'type'::TEXT,
            public.smoothing_normalize_token(t.type),
            NULLIF(BTRIM(t.type), '')
        FROM training t

        UNION ALL

        SELECT
            t.as_of_date,
            t.project_id,
            'category_type'::TEXT,
            CONCAT(
                                public.smoothing_normalize_token(t.category),
                '|',
                                public.smoothing_normalize_token(t.type)
            ),
            CONCAT(NULLIF(BTRIM(t.category), ''), ' / ', NULLIF(BTRIM(t.type), ''))
        FROM training t
                WHERE public.smoothing_normalize_token(t.category) IS NOT NULL
                    AND public.smoothing_normalize_token(t.type) IS NOT NULL

        UNION ALL

        SELECT
            t.as_of_date,
            t.project_id,
            'product'::TEXT,
            public.smoothing_normalize_token(product_token.token),
            NULLIF(BTRIM(product_token.token), '')
        FROM training t
        CROSS JOIN LATERAL REGEXP_SPLIT_TO_TABLE(
            COALESCE(t.raw_product_mirror, ''),
            '[[:space:]]*,[[:space:]]*'
        ) AS product_token(token)

        UNION ALL

        SELECT
            t.as_of_date,
            t.project_id,
            'account'::TEXT,
            public.smoothing_normalize_token(account_token.token),
            NULLIF(BTRIM(account_token.token), '')
        FROM training t
        CROSS JOIN LATERAL REGEXP_SPLIT_TO_TABLE(
            COALESCE(t.raw_account_mirror, ''),
            '[[:space:]]*,[[:space:]]*'
        ) AS account_token(token)
    )
    SELECT
        rm.member_as_of_date AS as_of_date,
        rm.project_id,
        rm.dimension,
        rm.group_key,
        MIN(rm.group_display) AS group_display
    FROM raw_members rm
    WHERE rm.group_key IS NOT NULL
      AND rm.group_key <> ''
      AND rm.group_display IS NOT NULL
      AND rm.group_display <> ''
    GROUP BY
        rm.member_as_of_date,
        rm.project_id,
        rm.dimension,
        rm.group_key;
$$ LANGUAGE sql STABLE;

