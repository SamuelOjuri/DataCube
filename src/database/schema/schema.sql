CREATE OR REPLACE FUNCTION public.invoice_smoothing_as_of_date()
RETURNS DATE AS $$
    SELECT COALESCE(
        NULLIF(current_setting('datacube.smoothing_as_of_date', true), '')::DATE,
        CURRENT_DATE
    );
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION public.smoothing_normalize_token(raw_value TEXT)
RETURNS TEXT AS $$
    SELECT NULLIF(
        BTRIM(
            REGEXP_REPLACE(
                REGEXP_REPLACE(
                    REGEXP_REPLACE(
                        REGEXP_REPLACE(
                            REGEXP_REPLACE(
                                LOWER(BTRIM(COALESCE(raw_value, ''))),
                                '[[:space:]]*/[[:space:]]*', '/', 'g'
                            ),
                            '[[:space:]]*-[[:space:]]*', '-', 'g'
                        ),
                        '[[:space:]]*\([[:space:]]*', ' (', 'g'
                    ),
                    '[[:space:]]*\)[[:space:]]*', ')', 'g'
                ),
                '[[:space:]]+', ' ', 'g'
            )
        ),
        ''
    );
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION public.invoice_smoothing_training_rows(
    p_as_of_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
    as_of_date DATE,
    mature_cutoff_date DATE,
    project_id TEXT,
    project_name TEXT,
    category TEXT,
    type TEXT,
    raw_account_mirror TEXT,
    raw_product_mirror TEXT,
    first_date_invoiced DATE,
    last_date_invoiced DATE,
    invoicing_spread_days INTEGER,
    is_smoothed BOOLEAN,
    is_mature BOOLEAN
) AS $$
    SELECT
        COALESCE(p_as_of_date, CURRENT_DATE) AS as_of_date,
        (COALESCE(p_as_of_date, CURRENT_DATE) - INTERVAL '180 days')::DATE AS mature_cutoff_date,
        p.monday_id AS project_id,
        COALESCE(NULLIF(BTRIM(p.project_name), ''), p.item_name) AS project_name,
        NULLIF(BTRIM(p.category), '') AS category,
        NULLIF(BTRIM(p.type), '') AS type,
        NULLIF(BTRIM(p.account), '') AS raw_account_mirror,
        NULLIF(BTRIM(p.product_type), '') AS raw_product_mirror,
        p.first_date_invoiced,
        p.last_date_invoiced,
        p.invoicing_spread_days,
        (p.last_date_invoiced > p.first_date_invoiced) AS is_smoothed,
        (
            p.first_date_invoiced <=
            (COALESCE(p_as_of_date, CURRENT_DATE) - INTERVAL '180 days')::DATE
        ) AS is_mature
    FROM public.projects p
    WHERE p.first_date_invoiced IS NOT NULL
      AND p.last_date_invoiced IS NOT NULL;
$$ LANGUAGE sql STABLE;

