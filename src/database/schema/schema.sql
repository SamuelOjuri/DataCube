FROM public.invoice_smoothing_signal_members(public.invoice_smoothing_as_of_date()::DATE);

CREATE OR REPLACE FUNCTION public.invoice_smoothing_signal_rows(
    p_as_of_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
    as_of_date DATE,
    dimension TEXT,
    group_key TEXT,
    group_display TEXT,
    all_project_count BIGINT,
    all_smoothed_count BIGINT,
    all_smoothed_pct NUMERIC(8,6),
    mature_project_count BIGINT,
    mature_smoothed_count BIGINT,
    mature_smoothed_pct NUMERIC(8,6),
    shrunk_mature_smoothed_pct NUMERIC(8,6),
    shrinkage_k INTEGER,
    mature_spread_days_sum NUMERIC(14,2),
    mature_avg_spread_days NUMERIC(10,2),
    mature_expected_spread_days NUMERIC(10,2),
    avg_spread_if_smoothed NUMERIC(10,2),
    median_smoothed_days NUMERIC(10,2),
    p75_smoothed_days NUMERIC(10,2),
    rate_90_plus_days NUMERIC(8,6),
    rate_180_plus_days NUMERIC(8,6),
    confidence TEXT,
    suggested_use TEXT
) AS $$
    WITH training AS (
        SELECT *
        FROM public.invoice_smoothing_training_rows(COALESCE(p_as_of_date, CURRENT_DATE)::DATE)
    ),
    members AS (
        SELECT *
        FROM public.invoice_smoothing_signal_members(COALESCE(p_as_of_date, CURRENT_DATE)::DATE)
    ),
    member_rows AS (
        SELECT
            m.as_of_date,
            m.dimension,
            m.group_key,
            m.group_display,
            t.project_id,
            t.invoicing_spread_days,
            t.is_smoothed,
            t.is_mature
        FROM members m
        INNER JOIN training t
            ON t.as_of_date = m.as_of_date
           AND t.project_id = m.project_id
    ),
    global_stats AS (
        SELECT
            COUNT(*) AS global_all_project_count,
            COUNT(*) FILTER (WHERE t.is_smoothed) AS global_all_smoothed_count,
            COUNT(*) FILTER (WHERE t.is_mature) AS global_mature_project_count,
            COUNT(*) FILTER (WHERE t.is_mature AND t.is_smoothed) AS global_mature_smoothed_count,
            COUNT(*) FILTER (
                WHERE t.is_mature AND t.invoicing_spread_days >= 90
            ) AS global_mature_90_plus_count,
            COUNT(*) FILTER (
                WHERE t.is_mature AND t.invoicing_spread_days >= 180
            ) AS global_mature_180_plus_count,
            COALESCE(
                SUM(t.invoicing_spread_days) FILTER (WHERE t.is_mature),
                0
            )::NUMERIC AS global_mature_spread_days_sum,
            AVG(t.invoicing_spread_days::NUMERIC) FILTER (WHERE t.is_mature) AS global_mature_avg_spread_days_raw,
            AVG(t.invoicing_spread_days::NUMERIC) FILTER (
                WHERE t.is_mature AND t.is_smoothed
            ) AS global_avg_spread_if_smoothed,
            PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY t.invoicing_spread_days)
                FILTER (WHERE t.is_mature AND t.is_smoothed) AS global_median_smoothed_days,
            PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY t.invoicing_spread_days)
                FILTER (WHERE t.is_mature AND t.is_smoothed) AS global_p75_smoothed_days
        FROM training t
    ),
    global_rates AS (
        SELECT
            gs.*,
            CASE
                WHEN gs.global_mature_project_count > 0 THEN
                    gs.global_mature_smoothed_count::NUMERIC / gs.global_mature_project_count
                ELSE 0::NUMERIC
            END AS global_mature_rate,
            CASE
                WHEN gs.global_mature_project_count > 0 THEN
                    gs.global_mature_spread_days_sum / gs.global_mature_project_count
                ELSE 0::NUMERIC
            END AS global_mature_avg_spread_days
        FROM global_stats gs
    ),
    group_stats AS (
        SELECT
            mr.as_of_date,
            mr.dimension,
            mr.group_key,
            MIN(mr.group_display) AS group_display,
            COUNT(DISTINCT mr.project_id) AS all_project_count,
            COUNT(DISTINCT mr.project_id) FILTER (WHERE mr.is_smoothed) AS all_smoothed_count,
            COUNT(DISTINCT mr.project_id) FILTER (WHERE mr.is_mature) AS mature_project_count,
            COUNT(DISTINCT mr.project_id) FILTER (WHERE mr.is_mature AND mr.is_smoothed) AS mature_smoothed_count,
            COUNT(DISTINCT mr.project_id) FILTER (
                WHERE mr.is_mature AND mr.invoicing_spread_days >= 90
            ) AS mature_90_plus_count,
            COUNT(DISTINCT mr.project_id) FILTER (
                WHERE mr.is_mature AND mr.invoicing_spread_days >= 180
            ) AS mature_180_plus_count,
            COALESCE(
                SUM(mr.invoicing_spread_days) FILTER (WHERE mr.is_mature),
                0
            )::NUMERIC AS mature_spread_days_sum,
            AVG(mr.invoicing_spread_days::NUMERIC) FILTER (WHERE mr.is_mature) AS mature_avg_spread_days,
            AVG(mr.invoicing_spread_days::NUMERIC) FILTER (
                WHERE mr.is_mature AND mr.is_smoothed
            ) AS avg_spread_if_smoothed,
            PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY mr.invoicing_spread_days)
                FILTER (WHERE mr.is_mature AND mr.is_smoothed) AS median_smoothed_days,
            PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY mr.invoicing_spread_days)
                FILTER (WHERE mr.is_mature AND mr.is_smoothed) AS p75_smoothed_days
        FROM member_rows mr
        GROUP BY mr.as_of_date, mr.dimension, mr.group_key
    )
    SELECT
        gs.as_of_date,
        gs.dimension,
        gs.group_key,
        gs.group_display,
        gs.all_project_count,
        gs.all_smoothed_count,
        ROUND(
            COALESCE(gs.all_smoothed_count::NUMERIC / NULLIF(gs.all_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS all_smoothed_pct,
        gs.mature_project_count,
        gs.mature_smoothed_count,
        ROUND(
            COALESCE(gs.mature_smoothed_count::NUMERIC / NULLIF(gs.mature_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS mature_smoothed_pct,
        ROUND(
            (
                gs.mature_smoothed_count::NUMERIC +
                (20::NUMERIC * gr.global_mature_rate)
            ) / (gs.mature_project_count + 20),
            6
        )::NUMERIC(8,6) AS shrunk_mature_smoothed_pct,
        20::INTEGER AS shrinkage_k,
        ROUND(gs.mature_spread_days_sum, 2)::NUMERIC(14,2) AS mature_spread_days_sum,
        ROUND(COALESCE(gs.mature_avg_spread_days, 0), 2)::NUMERIC(10,2) AS mature_avg_spread_days,
        ROUND(
            (
                gs.mature_spread_days_sum +
                (20::NUMERIC * gr.global_mature_avg_spread_days)
            ) / (gs.mature_project_count + 20),
            2
        )::NUMERIC(10,2) AS mature_expected_spread_days,
        ROUND(COALESCE(gs.avg_spread_if_smoothed, 0), 2)::NUMERIC(10,2) AS avg_spread_if_smoothed,
        ROUND(COALESCE(gs.median_smoothed_days, 0)::NUMERIC, 2)::NUMERIC(10,2) AS median_smoothed_days,
        ROUND(COALESCE(gs.p75_smoothed_days, 0)::NUMERIC, 2)::NUMERIC(10,2) AS p75_smoothed_days,
        ROUND(
            COALESCE(gs.mature_90_plus_count::NUMERIC / NULLIF(gs.mature_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS rate_90_plus_days,
        ROUND(
            COALESCE(gs.mature_180_plus_count::NUMERIC / NULLIF(gs.mature_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS rate_180_plus_days,
        CASE
            WHEN gs.mature_project_count >= 50 THEN 'High'
            WHEN gs.mature_project_count >= 15 THEN 'Medium'
            WHEN gs.mature_project_count >= 5 THEN 'Low'
            ELSE 'Very low'
        END AS confidence,
        CASE
            WHEN gs.mature_project_count >= 50 THEN 'Use directly'
            WHEN gs.mature_project_count >= 15 THEN 'Use with shrinkage'
            WHEN gs.mature_project_count >= 5 THEN 'Directional only'
            ELSE 'Use global fallback'
        END AS suggested_use
    FROM group_stats gs
    CROSS JOIN global_rates gr

    UNION ALL

    SELECT
        COALESCE(p_as_of_date, CURRENT_DATE) AS as_of_date,
        'global'::TEXT AS dimension,
        '__global__'::TEXT AS group_key,
        'Global mature fallback'::TEXT AS group_display,
        gr.global_all_project_count AS all_project_count,
        gr.global_all_smoothed_count AS all_smoothed_count,
        ROUND(
            COALESCE(gr.global_all_smoothed_count::NUMERIC / NULLIF(gr.global_all_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS all_smoothed_pct,
        gr.global_mature_project_count AS mature_project_count,
        gr.global_mature_smoothed_count AS mature_smoothed_count,
        ROUND(gr.global_mature_rate, 6)::NUMERIC(8,6) AS mature_smoothed_pct,
        ROUND(gr.global_mature_rate, 6)::NUMERIC(8,6) AS shrunk_mature_smoothed_pct,
        20::INTEGER AS shrinkage_k,
        ROUND(gr.global_mature_spread_days_sum, 2)::NUMERIC(14,2) AS mature_spread_days_sum,
        ROUND(COALESCE(gr.global_mature_avg_spread_days_raw, 0), 2)::NUMERIC(10,2) AS mature_avg_spread_days,
        ROUND(gr.global_mature_avg_spread_days, 2)::NUMERIC(10,2) AS mature_expected_spread_days,
        ROUND(COALESCE(gr.global_avg_spread_if_smoothed, 0), 2)::NUMERIC(10,2) AS avg_spread_if_smoothed,
        ROUND(COALESCE(gr.global_median_smoothed_days, 0)::NUMERIC, 2)::NUMERIC(10,2) AS median_smoothed_days,
        ROUND(COALESCE(gr.global_p75_smoothed_days, 0)::NUMERIC, 2)::NUMERIC(10,2) AS p75_smoothed_days,
        ROUND(
            COALESCE(gr.global_mature_90_plus_count::NUMERIC / NULLIF(gr.global_mature_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS rate_90_plus_days,
        ROUND(
            COALESCE(gr.global_mature_180_plus_count::NUMERIC / NULLIF(gr.global_mature_project_count, 0), 0),
            6
        )::NUMERIC(8,6) AS rate_180_plus_days,
        CASE
            WHEN gr.global_mature_project_count >= 50 THEN 'High'
            WHEN gr.global_mature_project_count >= 15 THEN 'Medium'
            WHEN gr.global_mature_project_count >= 5 THEN 'Low'
            ELSE 'Very low'
        END AS confidence,
        'Global fallback'::TEXT AS suggested_use
    FROM global_rates gr;
$$ LANGUAGE sql STABLE;

