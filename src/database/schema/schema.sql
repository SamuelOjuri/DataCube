            FILTER (WHERE t.group_key IS NOT NULL) AS candidate_group_keys,
        STRING_AGG(DISTINCT t.group_display, ', ' ORDER BY t.group_display)
            FILTER (WHERE t.group_display IS NOT NULL) AS candidate_group_displays,
        STRING_AGG(DISTINCT s.group_key, ', ' ORDER BY s.group_key)
            FILTER (WHERE s.group_key IS NOT NULL) AS matched_group_keys,
        STRING_AGG(DISTINCT s.group_display, ', ' ORDER BY s.group_display)
