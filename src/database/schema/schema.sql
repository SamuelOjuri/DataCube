-- Stage 5: Smoothed monthly revenue allocation
-- =========================================================

CREATE MATERIALIZED VIEW mv_pipeline_smoothed_revenue_monthly_12m_v1 AS
WITH bounds AS (
    SELECT
        DATE_TRUNC('month', CURRENT_DATE)::DATE AS window_start,
        (DATE_TRUNC('month', CURRENT_DATE) + INTERVAL '12 months')::DATE AS window_end
),
scored_projects AS (
    SELECT
        s.project_id,
        s.stage_bucket,
        s.forecast_date::DATE AS forecast_date,
        s.forecast_month,
        COALESCE(s.expected_value, 0::NUMERIC)::NUMERIC AS expected_value,
        GREATEST(
            0::NUMERIC,
            LEAST(1::NUMERIC, COALESCE(s.combined_smoothed_probability, 0::NUMERIC))
        ) AS smoothing_probability,
        GREATEST(0::NUMERIC, COALESCE(s.expected_spread_days, 0::NUMERIC)) AS expected_spread_days
    FROM vw_pipeline_smoothing_score_v1 s
    CROSS JOIN bounds b
    WHERE s.forecast_month >= b.window_start
      AND s.forecast_month < b.window_end
),
project_values AS (
    SELECT
        sp.*,
        (sp.expected_value * sp.smoothing_probability) AS smoothed_value,
        (sp.expected_value * (1::NUMERIC - sp.smoothing_probability)) AS unsmoothed_value,
        GREATEST(CEIL(sp.expected_spread_days)::INTEGER, 1) AS spread_day_count
    FROM scored_projects sp
),
allocation_periods AS (
    SELECT
        pv.*,
        b.window_start,
        b.window_end,
        LEAST((pv.forecast_date + pv.spread_day_count)::DATE, b.window_end) AS allocation_end_date
    FROM project_values pv
    CROSS JOIN bounds b
),
allocation_periods_with_days AS (
    SELECT
        ap.*,
        GREATEST(
            EXTRACT(EPOCH FROM (ap.allocation_end_date::TIMESTAMP - ap.forecast_date::TIMESTAMP))
                / 86400::NUMERIC,
            1::NUMERIC
        ) AS allocation_day_count
    FROM allocation_periods ap
),
unsmoothed_allocations AS (
    SELECT
        ap.project_id,
        ap.stage_bucket,
        ap.forecast_month,
        ap.unsmoothed_value AS unsmoothed_allocated_value,
        0::NUMERIC AS smoothed_allocated_value
    FROM allocation_periods_with_days ap
),
smoothed_allocations AS (
    SELECT
        ap.project_id,
        ap.stage_bucket,
        allocation_month.month_start::DATE AS forecast_month,
        0::NUMERIC AS unsmoothed_allocated_value,
        (
            ap.smoothed_value *
            GREATEST(
                EXTRACT(EPOCH FROM (
                    LEAST(
                        ap.allocation_end_date::TIMESTAMP,
                        (allocation_month.month_start + INTERVAL '1 month')::TIMESTAMP
                    ) - GREATEST(
                        ap.forecast_date::TIMESTAMP,
                        allocation_month.month_start::TIMESTAMP
                    )
                )) / 86400::NUMERIC,
                0::NUMERIC
            ) / ap.allocation_day_count
        ) AS smoothed_allocated_value
    FROM allocation_periods_with_days ap
    CROSS JOIN LATERAL GENERATE_SERIES(
        DATE_TRUNC('month', ap.forecast_date)::DATE,
        DATE_TRUNC('month', (ap.allocation_end_date - INTERVAL '1 day')::DATE)::DATE,
        INTERVAL '1 month'
    ) AS allocation_month(month_start)
),
allocation_rows AS (
    SELECT *
    FROM unsmoothed_allocations

    UNION ALL

    SELECT *
    FROM smoothed_allocations
)
SELECT
    ar.forecast_month,
    ar.stage_bucket,
    COUNT(DISTINCT ar.project_id) AS project_count,
    COUNT(DISTINCT ar.project_id) FILTER (
        WHERE ar.unsmoothed_allocated_value <> 0
    ) AS unsmoothed_project_count,
    COUNT(DISTINCT ar.project_id) FILTER (
        WHERE ar.smoothed_allocated_value <> 0
    ) AS smoothed_project_count,
    ROUND(SUM(ar.unsmoothed_allocated_value), 2)::NUMERIC(14,2) AS unsmoothed_expected_value,
    ROUND(SUM(ar.smoothed_allocated_value), 2)::NUMERIC(14,2) AS smoothed_expected_value,
    ROUND(
        SUM(ar.unsmoothed_allocated_value + ar.smoothed_allocated_value),
        2
    )::NUMERIC(14,2) AS allocated_expected_value
FROM allocation_rows ar
CROSS JOIN bounds b
WHERE ar.forecast_month >= b.window_start
  AND ar.forecast_month < b.window_end
GROUP BY ar.forecast_month, ar.stage_bucket
ORDER BY ar.forecast_month, ar.stage_bucket;

CREATE UNIQUE INDEX IF NOT EXISTS idx_mv_pipeline_smoothed_revenue_monthly_12m_v1_unique
    ON mv_pipeline_smoothed_revenue_monthly_12m_v1 (forecast_month, stage_bucket);

CREATE INDEX IF NOT EXISTS idx_mv_pipeline_smoothed_revenue_monthly_12m_v1_forecast_month
    ON mv_pipeline_smoothed_revenue_monthly_12m_v1 (forecast_month);

COMMENT ON MATERIALIZED VIEW mv_pipeline_smoothed_revenue_monthly_12m_v1 IS
    'Phase 4 day-weighted monthly allocation of pipeline expected value using invoice smoothing scores.';


