-- Main projects table (Parent Board: 1825117125)
CREATE TABLE projects (
    -- Primary identifiers
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    monday_id TEXT UNIQUE NOT NULL,
    item_name TEXT NOT NULL,
    
    -- Core project fields
    project_name TEXT,
    pipeline_stage TEXT,
    status_category TEXT GENERATED ALWAYS AS (
        CASE
            WHEN pipeline_stage = 'Won - Closed (Invoiced)' THEN 'Won'
            WHEN pipeline_stage = 'Lost' THEN 'Lost'
            ELSE 'Open'
        END
    ) STORED,
    
    -- Categorical fields
    type TEXT,  -- New Build/Refurbishment
    category TEXT,  -- Apartments, Commercial, etc.
    zip_code TEXT,
    sales_representative TEXT,
    funding TEXT,
    
    -- Mirror resolved fields
    account TEXT,
    product_type TEXT,
    new_enquiry_value NUMERIC(12, 2) DEFAULT 0,
    
    -- Calculated fields
    gestation_period INTEGER CHECK (gestation_period >= 0 AND gestation_period <= 500000),
    project_value NUMERIC(12, 2),
    weighted_pipeline NUMERIC(12, 2),
    probability_percent INTEGER DEFAULT 0,
    
    -- Date fields
    date_created DATE,
    expected_start_date DATE,
    follow_up_date DATE,
    first_date_designed DATE,
    last_date_designed DATE,
    first_date_invoiced DATE,
    last_date_invoiced DATE,
    -- Always generated by Postgres from first_date_invoiced and last_date_invoiced.
    -- Do not INSERT or UPDATE this column from sync_service.py, backfill scripts, or API code.
    -- Rules:
    --   - NULL if either invoice date is missing.
    --   - 0 when first_date_invoiced = last_date_invoiced.
    --   - Otherwise, number of calendar days between first and last invoice dates.
    invoicing_spread_days INTEGER GENERATED ALWAYS AS (
        CASE
            WHEN first_date_invoiced IS NOT NULL
            AND last_date_invoiced IS NOT NULL
            THEN GREATEST(last_date_invoiced - first_date_invoiced, 0)
            ELSE NULL
        END
    ) STORED,

    -- Order fields
    total_order_value NUMERIC(12, 2),
    total_amount_invoiced NUMERIC(12, 2),
    date_order_received DATE,
    
    -- Feedback fields
    feedback TEXT,
    lost_to_who_or_why TEXT,
    
    -- Analysis fields
    value_band TEXT,  -- Computed during processing
    
    -- Metadata
    last_synced_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    sync_version INTEGER DEFAULT 1
);

